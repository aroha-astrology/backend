// =============================================================================
// Writes docs/AROHA_E2E_FEATURES_AND_CALCULATIONS_AUDITED.md
// =============================================================================
// The audited replacement of the older feature document. It is generated from the one place
// that is kept honest, the provenance registry (src/lib/astro-engine/rules/provenance.ts), the
// safety rules and the per-report basis (rules/report-basis.ts), so it cannot drift from the code.
//
//   npx tsx scripts/audit-feature-doc.ts
// =============================================================================

import { writeFileSync } from 'node:fs';
import { REPORT_CATALOGUE } from '../src/config/reports.js';
import {
  allProvenanceEntries,
  type ProvenanceTag,
} from '../src/lib/astro-engine/rules/provenance.js';
import { DEFAULT_PROFILE } from '../src/lib/astro-engine/rules/profile.js';
import { SAFETY_RULES, reportBasis } from '../src/lib/astro-engine/rules/report-basis.js';

const GROUPS: Array<[string, string]> = [
  ['PLN', 'Planet state (combustion, motion)'],
  ['SHB', 'Shadbala (six-fold strength)'],
  ['AKV', 'Ashtakavarga'],
  ['DIG', 'Dignity, aspects and friendship'],
  ['ASP', 'Aspects'],
  ['VCH', 'Divisional charts'],
  ['VMD', 'Vimshottari dasha'],
  ['CHD', 'Chara dasha'],
  ['YGN', 'Yogini dasha'],
  ['DOH', 'Doshas'],
  ['YGA', 'Yogas'],
  ['MT', 'Matching (Ashtakoota, Dashakoota)'],
  ['PAN', 'Panchang'],
  ['MUH', 'Muhurta'],
  ['PPK', 'Pancha Pakshi'],
  ['KP', 'Krishnamurti Paddhati'],
  ['TAJ', 'Varshaphal (older entries)'],
  ['TJK', 'Varshaphal (Tajika Neelakanthi)'],
  ['VAK', 'Retrograde (vakri) analysis'],
  ['LKB', 'Lal Kitab'],
  ['NUM', 'Numerology'],
  ['ACG', 'Astrocartography'],
  ['VST', 'Vastu'],
  ['PLM', 'Palmistry'],
  ['GEM', 'Gemstones'],
  ['YNT', 'Yantras'],
  ['REC', 'Birth-time rectification'],
  ['RPT', 'Reports'],
  ['ARCH', 'Architecture'],
];

const TAG_TEXT: Record<ProvenanceTag, string> = {
  ANCIENT_CLASSICAL: 'Ancient classical: an old primary text was opened and the rule is in it',
  LATER_CLASSICAL:
    'Later classical: a later text (Tajika, Uttara Kalamrita, Phaladeepika and the like)',
  MODERN_ASTROLOGICAL:
    'Modern: a 20th-century or later system (KP, Lal Kitab, numerology, Kaal Sarp)',
  AROHA_PROPRIETARY: "Aroha's own scoring, blending or wording",
  UNVERIFIED: 'Unverified: no old text has been found for it yet',
};

const cell = (s: string) => s.replace(/\|/g, '/').replace(/\r?\n/g, ' ').trim();
const entries = allProvenanceEntries();
const prefixOf = (id: string) => id.split('-')[0]!;

const out: string[] = [];
out.push('# Aroha: features and calculations, as audited');
out.push('');
out.push(
  'This document replaces the older end-to-end specification. It is written from what the engine does today and from where each rule comes from, and it is generated by `npx tsx scripts/audit-feature-doc.ts` from the provenance registry, so it cannot drift from the code. The reasoning behind each change is in `docs/engine-audit/` (the register of sources and the list of corrections).',
);
out.push('');
out.push(`Rule profile in force: \`${DEFAULT_PROFILE.id}\`.`);
out.push('');
out.push('## How to read the labels');
out.push('');
out.push('| Label | Meaning | Rules |');
out.push('| --- | --- | --- |');
for (const tag of Object.keys(TAG_TEXT) as ProvenanceTag[]) {
  out.push(`| ${tag} | ${TAG_TEXT[tag]} | ${entries.filter((e) => e.tag === tag).length} |`);
}
out.push('');
out.push(
  'A rule is never called ancient, classical or scriptural in the app unless its label says so. Aroha is traditional astrology offered for reflection, not medical, legal or financial advice.',
);
out.push('');
out.push('## Where the older document was wrong');
out.push('');
out.push('| Area | The older document | What the engine does |');
out.push('| --- | --- | --- |');
out.push(
  '| Zero-math AI | "Pure deterministic engine" for everything | The chart, strengths, dashas, doshas and matching are computed by code; the wording of reports and chat is written by a language model that is given those facts and is told not to invent any. Reports also carry a scoring layer that is Aroha\'s own |',
);
out.push('| Tribhaga Bala | 30 virupas | 60 virupas (one rupa), BPHS 27.12 |');
out.push('| Choghadiya | Fixed 1.5 hours | The real length of the day divided by eight |');
out.push('| Pancha Pakshi | Fixed 2.4 hours | The real sunrise and sunset of the place |');
out.push('| Uchcha Bala | Linear distance | The circular distance from the debilitation point |');
out.push(
  '| Yogas | "100+" | The named yogas the engine detects are fewer (about 57); the count is not a feature |',
);
out.push('| Rectification | Vague window | Plus or minus 60 minutes in 4-minute steps |');
out.push('| Sahams | Eight | Five, each with its own formula; unverified |');
out.push(
  '| Metrologist agent | Implied a language-model agent | A deterministic chart computation, now called the ephemeris service |',
);
out.push(
  '| Daily lucky number | Personal, from the nakshatra | "Today\'s number": the day of the month added down to one digit, the same for everyone (NM2) |',
);
out.push('| Kemadruma | Severe | Follows the Brihat Jataka; at most "moderate" in the app |');
out.push(
  '| Progeny report | Sex tendency and number of children | Neither is shown or written any more (SF2) |',
);
out.push('| Baby-name report | Doshas of the child | None are mentioned (BN2) |');
out.push('');

out.push('## Features by area');
out.push('');
const seen = new Set<string>();
for (const [prefix, title] of GROUPS) {
  const rows = entries.filter((e) => prefixOf(e.featureId) === prefix);
  if (rows.length === 0) continue;
  seen.add(prefix);
  out.push(`### ${title}`);
  out.push('');
  out.push('| Id | Feature | Label | Source | Note |');
  out.push('| --- | --- | --- | --- | --- |');
  for (const e of rows) {
    out.push(
      `| ${e.featureId} | ${cell(e.featureName)} | ${e.tag} | ${cell(e.sourceIds.join(', ')) || '-'} | ${cell(e.note ?? '')} |`,
    );
  }
  out.push('');
}
const rest = entries.filter((e) => !seen.has(prefixOf(e.featureId)));
if (rest.length > 0) {
  out.push('### Other');
  out.push('');
  out.push('| Id | Feature | Label | Source | Note |');
  out.push('| --- | --- | --- | --- | --- |');
  for (const e of rest) {
    out.push(
      `| ${e.featureId} | ${cell(e.featureName)} | ${e.tag} | ${cell(e.sourceIds.join(', ')) || '-'} | ${cell(e.note ?? '')} |`,
    );
  }
  out.push('');
}

out.push('## The sixteen reports');
out.push('');
out.push(
  'Every report returns a basis block (calculation basis, rule profile, rules by origin, safety class) and its narration carries the origin rule and the safety rule of its subject.',
);
out.push('');
out.push('| Report | Safety class | Traditional | Modern | Aroha own | Unverified |');
out.push('| --- | --- | --- | --- | --- | --- |');
for (const r of REPORT_CATALOGUE) {
  const b = reportBasis(r.key)!;
  out.push(
    `| ${r.key} | ${b.safety_classification} | ${b.traditional_rules.length} | ${b.modern_rules.length} | ${b.aroha_proprietary_rules.length} | ${b.unverified_rules.length} |`,
  );
}
out.push('');
out.push('### Safety rules');
out.push('');
for (const [k, v] of Object.entries(SAFETY_RULES)) {
  if (v) out.push(`- **${k}**: ${v}`);
}
out.push('');

writeFileSync(
  new URL('../docs/AROHA_E2E_FEATURES_AND_CALCULATIONS_AUDITED.md', import.meta.url),
  out.join('\n'),
);
console.log(`wrote ${entries.length} features`);
